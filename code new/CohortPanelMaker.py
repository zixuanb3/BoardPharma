def normalize_firm_key(value: object) -> str:
    """Normalize firm names for event-partner and price-sample matching."""
    if pd.isna(value):
        return ""
    return str(value).strip().upper()


def normalize_product_key(value: object) -> str:
    """Normalize product names for price-sample matching."""
    if pd.isna(value):
        return ""
    return str(value).strip().upper()


@lru_cache(maxsize=1)
def load_atc3_product_panel() -> pd.DataFrame:
    """Load the complete price-sample ATC3 market without roster filtering."""
    required = ["BoardName", "year", "quarter", "product", "atc3"]
    if not ATC3_PRICE_SAMPLE_PATH.exists():
        raise FileNotFoundError(f"Missing ATC3 price sample: {ATC3_PRICE_SAMPLE_PATH}")
    price = pd.read_csv(
        ATC3_PRICE_SAMPLE_PATH,
        usecols=required,
        low_memory=False,
    ).dropna(subset=required)
    price["BoardName"] = price["BoardName"].astype(str).str.strip()
    price["product"] = price["product"].astype(str).str.strip()
    price["atc3"] = price["atc3"].astype(str).str.strip()
    price["year"] = pd.to_numeric(price["year"], errors="raise").astype(int)
    price["quarter"] = pd.to_numeric(price["quarter"], errors="raise").astype(int)
    if not price["quarter"].between(1, 4).all():
        raise ValueError("ATC3 price sample contains invalid quarter values")
    price["_time_id"] = price["year"] * 4 + price["quarter"] - 1
    price["_firm_key"] = price["BoardName"].map(normalize_firm_key)
    price["_product_key"] = price["product"].map(normalize_product_key)
    return price.drop_duplicates(
        subset=["_time_id", "_firm_key", "product", "atc3"]
    ).reset_index(drop=True)


@lru_cache(maxsize=2)
def load_atc3_market_indices(panel_level: str) -> tuple[dict, dict]:
    """Build cached event-period firm/product ATC3 indices."""
    market = load_atc3_product_panel()
    if panel_level == "year":
        # Annual events are anchored at Q1, so annual sharing also uses Q1.
        market = market.loc[market["quarter"].eq(1)].copy()
        market["_panel_time"] = market["year"]
    elif panel_level == "quarter":
        market = market.copy()
        market["_panel_time"] = market["_time_id"]
    else:
        raise ValueError("panel_level must be 'year' or 'quarter'")

    partner_index = (
        market.groupby(["_panel_time", "_firm_key"])["atc3"]
        .agg(lambda values: set(values))
        .to_dict()
    )
    product_index = (
        market.groupby(["_panel_time", "_firm_key", "_product_key"])["atc3"]
        .agg(lambda values: set(values))
        .to_dict()
    )
    return partner_index, product_index


