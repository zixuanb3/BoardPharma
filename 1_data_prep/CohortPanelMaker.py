    def draw_stacked_req2_plot(
        self,
        years: list[int],
        treated_counts: list[int],
        segment_counts: dict[str, list[int]],
        plot_segments: list[str],
        unit_config: dict,
        title: str,
        out_path: Path,
    ) -> None:
        x = list(range(len(years)))
        width = 0.35
        plt.figure(figsize=(14, 6))

        bars_treated = plt.bar(
            [index - width / 2 for index in x],
            treated_counts,
            width=width,
            label="Treated",
        )
        control_bottom = [0] * len(years)
        for segment in plot_segments:
            values = segment_counts[segment]
            plt.bar(
                [index + width / 2 for index in x],
                values,
                width=width,
                bottom=control_bottom,
                label=f"Control: {segment}",
                color=REQ2_STACK_COLORS[segment],
            )
            control_bottom = [bottom + value for bottom, value in zip(control_bottom, values)]

        self.finish_plot(
            years=years,
            bars_to_label=[bars_treated],
            extra_totals=control_bottom,
            unit_config=unit_config,
            title=title,
            out_path=out_path,
        )

    def draw_two_bar_plot(
        self,
        years: list[int],
        treated_counts: list[int],
        control_counts: list[int],
        unit_config: dict,
        title: str,
        out_path: Path,
    ) -> None:
        x = list(range(len(years)))
        width = 0.35
        plt.figure(figsize=(14, 6))
        bars_treated = plt.bar(
            [index - width / 2 for index in x],
            treated_counts,
            width=width,
            label="Treated",
        )
        bars_control = plt.bar(
            [index + width / 2 for index in x],
            control_counts,
            width=width,
            label="Control",
        )
        self.finish_plot(
            years=years,
            bars_to_label=[bars_treated, bars_control],
            extra_totals=None,
            unit_config=unit_config,
            title=title,
            out_path=out_path,
        )

    def finish_plot(
        self,
        years: list[int],
        bars_to_label: list,
        extra_totals: list[int] | None,
        unit_config: dict,
        title: str,
        out_path: Path,
    ) -> None:
        for bars in bars_to_label:
            for bar in bars:
                height = bar.get_height()
                plt.text(
                    bar.get_x() + bar.get_width() / 2,
                    height + 1,
                    f"{int(height)}",
                    ha="center",
                    va="bottom",
                    fontsize=10,
                )

        if extra_totals is not None:
            x = list(range(len(years)))
            for xpos, total in zip([index + 0.35 / 2 for index in x], extra_totals):
                plt.text(
                    xpos,
                    total + 1,
                    f"{int(total)}",
                    ha="center",
                    va="bottom",
                    fontsize=10,
                )

        plt.xticks(list(range(len(years))), years, rotation=45)
        plt.ylabel(unit_config["ylabel"])
        plt.title(title)
        plt.legend()
        plt.tight_layout()
        out_path.parent.mkdir(parents=True, exist_ok=True)
        plt.savefig(out_path)
        plt.close()


